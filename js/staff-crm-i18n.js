  var currentLang = "en";
  var listeners = [];

  function normalizeLang(raw) {
    var v = String(raw || "").trim().toLowerCase();
    return v === "es" || v === "spanish" || v === "espanol" || v === "español" ? "es" : "en";
  }

  function interpolate(str, vars) {
    if (!vars) return str;
    return String(str).replace(/\{(\w+)\}/g, function (_, key) {
      return vars[key] != null ? String(vars[key]) : "";
    });
  }

  function t(key, vars) {
    var bucket = STRINGS[currentLang] || STRINGS.en;
    var fallback = STRINGS.en[key];
    var val = bucket[key] != null ? bucket[key] : fallback != null ? fallback : key;
    return interpolate(val, vars);
  }

  function getLang() {
    return currentLang;
  }

  function logoPath(lang) {
    return lang === "es" ? "/img/logo-spanish2.png" : "/img/logo-english2.png";
  }

  function setLang(lang, opts) {
    opts = opts || {};
    var next = normalizeLang(lang);
    if (next === currentLang && !opts.force) return;
    currentLang = next;
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch (e) {}
    document.documentElement.lang = next === "es" ? "es" : "en";
    document.documentElement.classList.toggle("lang-es", next === "es");
    document.documentElement.classList.toggle("lang-en", next === "en");
    if (!opts.silent) {
      listeners.forEach(function (fn) {
        try {
          fn(next);
        } catch (e) {}
      });
    }
  }

  function onLangChange(fn) {
    if (typeof fn === "function") listeners.push(fn);
  }

  function initLang() {
    var stored = "";
    try {
      stored = localStorage.getItem(STORAGE_KEY) || "";
    } catch (e) {}
    setLang(stored || "en", { force: true, silent: true });
  }

  initLang();

  window.StaffCrmI18n = {
    t: t,
    getLang: getLang,
    setLang: setLang,
    onLangChange: onLangChange,
    logoPath: logoPath,
  };

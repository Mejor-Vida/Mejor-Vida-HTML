-- Migration 014: Create quote_ranges table for WhatsApp bot quote engine
-- This table stores pre-computed Low/High/Anchor price ranges for $10K Final Expense coverage.
-- Low  = cheapest good-health (Level/Immediate) monthly premium across MOO + AmAm
-- High = cheapest bad-health (Graded/Modified) monthly premium across MOO + AmAm
-- Anchor = midpoint of Low and High
-- Source data: MOO Living Promise (NE) + American Amicable GS rates
-- Coverage: $10,000 face amount only. Prices scale proportionally for other amounts.

CREATE TABLE IF NOT EXISTS quote_ranges (
  id          serial PRIMARY KEY,
  age         smallint     NOT NULL,
  sex         text         NOT NULL CHECK (sex IN ('male','female')),
  smoker      boolean      NOT NULL DEFAULT false,
  low         numeric(7,2) NOT NULL,  -- cheapest good-health monthly premium ($10K)
  high        numeric(7,2) NOT NULL,  -- cheapest bad-health monthly premium ($10K)
  anchor      numeric(7,2) NOT NULL,  -- midpoint of low and high
  created_at  timestamptz  NOT NULL DEFAULT now(),
  UNIQUE (age, sex, smoker)
);

COMMENT ON TABLE  quote_ranges IS 'Pre-computed $10K FE quote ranges for WhatsApp bot (MOO + AmAm, NE rates)';
COMMENT ON COLUMN quote_ranges.low    IS 'Cheapest good-health (Level/Immediate) monthly premium for $10K';
COMMENT ON COLUMN quote_ranges.high   IS 'Cheapest bad-health (Graded) monthly premium for $10K';
COMMENT ON COLUMN quote_ranges.anchor IS 'Midpoint of low and high';

-- Enable RLS (service-role key reads; no public writes)
ALTER TABLE quote_ranges ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "service_role_all" ON quote_ranges;
CREATE POLICY "service_role_all" ON quote_ranges FOR ALL USING (true) WITH CHECK (true);


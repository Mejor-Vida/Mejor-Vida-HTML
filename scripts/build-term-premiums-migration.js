#!/usr/bin/env node
/**
 * Build SQL migration from term_carrier_premiums.csv
 *
 *   node scripts/build-term-premiums-migration.js
 */
"use strict";

const fs = require("fs");
const path = require("path");

const CSV_PATH = path.join(
  __dirname,
  "../integrations/knowledge/Term_Life_Knowledge/term_carrier_premiums.csv"
);
const OUT_PATH = path.join(
  __dirname,
  "../integrations/supabase/migrations/063_term_carrier_premiums_seed.sql"
);

function parseCsv(text) {
  const lines = text
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
  if (!lines.length) return [];
  const header = lines[0].split(",").map((h) => h.trim());
  return lines.slice(1).map((line) => {
    const parts = line.split(",");
    const row = {};
    header.forEach((h, i) => {
      row[h] = (parts[i] || "").trim();
    });
    return row;
  });
}

function sqlVal(v) {
  if (v == null || v === "") return "NULL";
  if (/^(true|false)$/i.test(v)) return v.toLowerCase();
  if (/^\d+(\.\d+)?$/.test(v)) return v;
  return `'${String(v).replace(/'/g, "''")}'`;
}

function main() {
  const csvText = fs.readFileSync(CSV_PATH, "utf8");
  const rows = parseCsv(csvText).filter((r) => r.carrier && r.age);

  let sql = `-- Generated by scripts/build-term-premiums-migration.js — ${new Date().toISOString().slice(0, 10)}\n`;
  sql += `-- Source: integrations/knowledge/Term_Life_Knowledge/term_carrier_premiums.csv\n\n`;

  if (!rows.length) {
    sql += "-- No data rows in CSV yet. Add verified carrier rates, then re-run this script.\n";
    fs.writeFileSync(OUT_PATH, sql);
    console.log("No rows to seed. Wrote placeholder:", OUT_PATH);
    return;
  }

  sql += "INSERT INTO term_carrier_premiums\n";
  sql +=
    "  (carrier, product, state, age, sex, smoker, term_years, face_band_min, face_band_max, health_class, rate_per_thousand, policy_fee_annual, modal_monthly_factor, monthly_premium, face_amount, source_file, source_date)\nVALUES\n";

  const values = rows.map((r) => {
    const smoker = r.smoker === "1" || r.smoker === "true" ? "true" : "false";
    return (
      `  (${sqlVal(r.carrier)}, ${sqlVal(r.product)}, ${sqlVal(r.state || "NE")}, ${sqlVal(r.age)}, ${sqlVal(r.sex)}, ${smoker}, ${sqlVal(r.term_years)}, ${sqlVal(r.face_band_min || 100000)}, ${sqlVal(r.face_band_max || 999999999)}, ${sqlVal(r.health_class)}, ${sqlVal(r.rate_per_thousand)}, ${sqlVal(r.policy_fee_annual)}, ${sqlVal(r.modal_monthly_factor || 0.086)}, ${sqlVal(r.monthly_premium)}, ${sqlVal(r.face_amount)}, ${sqlVal(r.source_file)}, ${sqlVal(r.source_date)})`
    );
  });

  sql += values.join(",\n");
  sql += "\nON CONFLICT (carrier, product, state, age, sex, smoker, term_years, face_band_min, face_band_max, health_class) DO UPDATE SET\n";
  sql +=
    "  rate_per_thousand = EXCLUDED.rate_per_thousand,\n  policy_fee_annual = EXCLUDED.policy_fee_annual,\n  modal_monthly_factor = EXCLUDED.modal_monthly_factor,\n  monthly_premium = EXCLUDED.monthly_premium,\n  face_amount = EXCLUDED.face_amount,\n  source_file = EXCLUDED.source_file,\n  source_date = EXCLUDED.source_date;\n";

  fs.writeFileSync(OUT_PATH, sql);
  console.log(`Wrote ${rows.length} rows to ${OUT_PATH}`);
}

main();

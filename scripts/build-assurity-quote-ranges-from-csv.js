#!/usr/bin/env node
/**
 * Build quote_ranges_assurity rows from integrations/knowledge/Assurity_Knowledge/
 * assurity_protect_plus_premiums_10k.csv — Assurity sources only.
 *
 * - Fills ages 18-44 with flyer_interpolated preferred_plus_nt when no row exists.
 * - Non-smoker range uses only NT classes present in CSV (no MOO ratios).
 * - Smoker rows only when tobacco classes exist in CSV.
 */
const fs = require("fs");
const path = require("path");

const CSV_PATH = path.join(
  __dirname,
  "../integrations/knowledge/Assurity_Knowledge/assurity_protect_plus_premiums_10k.csv"
);
const MIGRATION_050 = path.join(
  __dirname,
  "../integrations/supabase/migrations/050_quote_ranges_assurity.sql"
);
const MIGRATION_051 = path.join(
  __dirname,
  "../integrations/supabase/migrations/051_quote_ranges_assurity_assurity_only.sql"
);

const NT_CLASSES = ["preferred_plus_nt", "standard_nt"];
const TOBACCO_CLASSES = ["preferred_tobacco", "standard_tobacco"];
const FLYER_ANCHOR_AGES = [5, 25, 35, 45];

function parseCsv(text) {
  const lines = text
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
  const header = lines[0].split(",").map((h) => h.trim());
  return lines.slice(1).map((line) => {
    const parts = line.split(",");
    const row = {};
    header.forEach((h, i) => {
      row[h] = parts[i].trim();
    });
    row.age = parseInt(row.age, 10);
    row.monthly = parseFloat(row.monthly);
    return row;
  });
}

function interpolateFromFlyerAnchors(age, sex, bySexAge) {
  const points = {};
  for (const a of FLYER_ANCHOR_AGES) {
    const key = `${sex}:${a}`;
    if (bySexAge[key]) points[a] = bySexAge[key];
  }
  const ages = Object.keys(points)
    .map(Number)
    .sort((x, y) => x - y);
  if (!ages.length) return null;
  if (age <= ages[0]) return points[ages[0]];
  if (age >= ages[ages.length - 1]) return points[ages[ages.length - 1]];
  for (let i = 0; i < ages.length - 1; i++) {
    if (age >= ages[i] && age <= ages[i + 1]) {
      const t = (age - ages[i]) / (ages[i + 1] - ages[i]);
      return (
        Math.round((points[ages[i]] + t * (points[ages[i + 1]] - points[ages[i]])) * 100) /
        100
      );
    }
  }
  return points[ages[0]];
}

function buildPremiumMap(rows) {
  const map = new Map();
  for (const r of rows) {
    if (!Number.isFinite(r.age) || !Number.isFinite(r.monthly)) continue;
    const key = `${r.age}:${r.sex}:${r.uw_class}`;
    map.set(key, { monthly: r.monthly, source: r.source });
  }
  return map;
}

function getPremiums(map, age, sex, classes) {
  const vals = [];
  for (const uw of classes) {
    const hit = map.get(`${age}:${sex}:${uw}`);
    if (hit) vals.push(hit.monthly);
  }
  return vals;
}

function rangeFromPremiums(vals) {
  if (!vals.length) return null;
  const low = Math.min(...vals);
  const high = Math.max(...vals);
  const anchor = Math.round(((low + high) / 2) * 100) / 100;
  return {
    low: Math.round(low * 100) / 100,
    high: Math.round(high * 100) / 100,
    anchor,
  };
}

function main() {
  const csvText = fs.readFileSync(CSV_PATH, "utf8");
  const rows = parseCsv(csvText);
  const map = buildPremiumMap(rows);

  const flyerAnchors = {};
  for (const r of rows) {
    if (
      r.uw_class === "preferred_plus_nt" &&
      r.source === "flyer_rates_compare_rev_10_25"
    ) {
      flyerAnchors[`${r.sex}:${r.age}`] = r.monthly;
    }
  }

  for (let age = 18; age <= 44; age++) {
    for (const sex of ["male", "female"]) {
      const key = `${age}:${sex}:preferred_plus_nt`;
      if (!map.has(key)) {
        const monthly = interpolateFromFlyerAnchors(age, sex, flyerAnchors);
        if (monthly != null) {
          map.set(key, { monthly, source: "flyer_interpolated" });
        }
      }
    }
  }

  const quoteRows = [];
  for (let age = 18; age <= 44; age++) {
    for (const sex of ["male", "female"]) {
      const ntVals = getPremiums(map, age, sex, NT_CLASSES);
      const ntRange = rangeFromPremiums(ntVals);
      if (ntRange) {
        quoteRows.push({
          age,
          sex,
          smoker: false,
          ...ntRange,
        });
      }

      const tobaccoVals = getPremiums(map, age, sex, TOBACCO_CLASSES);
      const tobaccoRange = rangeFromPremiums(tobaccoVals);
      if (tobaccoRange) {
        quoteRows.push({
          age,
          sex,
          smoker: true,
          ...tobaccoRange,
        });
      }
    }
  }

  const header = `-- Regenerated by scripts/build-assurity-quote-ranges-from-csv.js
-- Assurity-only premiums: ${path.basename(CSV_PATH)}
-- Non-smoker: min/max of real NT classes (no MOO estimates).
-- Smoker: only when preferred_tobacco / standard_tobacco rows exist in CSV.

INSERT INTO quote_ranges_assurity (age, sex, smoker, low, high, anchor) VALUES
`;

  const vals = quoteRows
    .map(
      (r) =>
        `  (${r.age}, '${r.sex}', ${r.smoker}, ${r.low}, ${r.high}, ${r.anchor})`
    )
    .join(",\n");

  const footer = `
ON CONFLICT (age, sex, smoker) DO UPDATE SET
  low = EXCLUDED.low,
  high = EXCLUDED.high,
  anchor = EXCLUDED.anchor;
`;

  const reseedSql = `-- Migration 051: Reseed Assurity quote table (Assurity sources only; removes MOO-derived spreads)
-- Run after updating integrations/knowledge/Assurity_Knowledge/assurity_protect_plus_premiums_10k.csv

TRUNCATE quote_ranges_assurity;

${header}${vals}${footer}
`;

  fs.writeFileSync(MIGRATION_051, reseedSql);

  const flyerOnly = rows.filter((r) => r.source.startsWith("flyer"));
  const interpolated = quoteRows.filter((r) => !r.smoker).length;
  const smokerRows = quoteRows.filter((r) => r.smoker).length;

  console.log("CSV rows:", rows.length);
  console.log("Quote rows (18-44):", quoteRows.length);
  console.log("  non-smoker:", interpolated);
  console.log("  smoker (real tobacco classes only):", smokerRows);
  console.log("Wrote", MIGRATION_051);
  if (!smokerRows) {
    console.log(
      "Note: No tobacco premiums in CSV — smoker quotes will return no_data until Agent Center rows are added."
    );
  }
}

main();

"""Extra instructions appended to browser-use Agent extend_system_message."""

import os


def agent_critical_preface() -> str:
    """
    Placed **first** in extend_system_message so models see hard constraints before long policy text.
    """
    assurity_login = (
        os.getenv("ASSURITY_AGENT_LOGIN_URL") or "https://agentcenter.assurity.com/auth/login"
    ).strip()
    return (
        "**CRITICAL — read first (overrides lazy habits):**\n"
        "1. **No ‘inform user’ spam:** You may **not** spend multiple consecutive steps only telling the user a portal is "
        "**unavailable** or to **check back later**. **Maximum one** such message for a given situation — then you must "
        "**change action** (e.g. navigate again to the **exact official login URL**) or **stop** with URL + what the "
        "page actually shows.\n"
        "2. **‘Unavailable’ needs proof:** Saying a site is down requires **visible** evidence (maintenance banner, "
        "browser error page, explicit connection failure text). A **slow load, spinner, white screen, or stuck automation** "
        "is **not** proof the carrier site is offline.\n"
        "3. **Open login for the user to sign in:** First productive step = **go to the real login URL** (from the task, "
        "carrier docs, or context — for Assurity Agent Center use this URL unless the task gives another: "
        f"`{assurity_login}`). "
        "**Do not** chain many passive “wait to see if it loads” steps on the wrong or blank page before navigating.\n"
        "4. After **one** failed load cycle: give a **single** concise summary (current URL, visible title/error) — **do not** "
        "repeat the same ‘unavailable’ narrative for many steps.\n"
    )


